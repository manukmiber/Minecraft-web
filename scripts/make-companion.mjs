/**
 * Renders the companion character's artwork.
 *
 * The painter itself lives in `src/core/generators/skin/`, in TypeScript, next
 * to the body spec it draws against — this script only bundles it, runs it and
 * writes the PNGs out. Keeping the art *in the app's source* rather than in this
 * script is what lets the 3D preview, the pixel editor's UV template and the
 * exported pack all agree about where the fringe ends.
 *
 *     node scripts/make-companion.mjs [--scale 4]
 *
 * Writes `public/textures/companion/kohane/**` plus the manifest at
 * `src/core/data/companionTextures.ts`. Everything is deterministic, so a re-run
 * with no source change leaves the working tree clean.
 */

import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { createHash } from 'node:crypto'

import esbuild from 'esbuild'

import { encodePng } from './faithful-png.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = path.join(ROOT, 'public/textures/companion/kohane')
const MANIFEST = path.join(ROOT, 'src/core/data/companionTextures.ts')
const OUT_REL = 'textures/companion/kohane'

const scaleArg = process.argv.indexOf('--scale')
const SCALE = scaleArg > 0 ? Number(process.argv[scaleArg + 1]) : 4

/** Bundles a TypeScript entry point and imports it. */
async function loadModule(entry, exports) {
  const outfile = path.join(ROOT, 'node_modules/.tmp', `companion-${Date.now()}.mjs`)
  fs.mkdirSync(path.dirname(outfile), { recursive: true })
  await esbuild.build({
    entryPoints: [path.join(ROOT, entry)],
    bundle: true,
    format: 'esm',
    platform: 'node',
    outfile,
    logLevel: 'warning',
    absWorkingDir: ROOT,
  })
  const loaded = await import(pathToFileURL(outfile).href)
  fs.rmSync(outfile, { force: true })
  for (const name of exports) {
    if (!(name in loaded)) throw new Error(`${entry} does not export ${name}`)
  }
  return loaded
}

function writePng(file, canvas) {
  const bytes = encodePng({
    width: canvas.width,
    height: canvas.height,
    pixels: Buffer.from(canvas.data),
  })
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, bytes)
  return bytes
}

const skin = await loadModule('src/core/generators/skin/companionSkin.ts', ['paintCompanion'])
const egg = await loadModule('src/core/generators/skin/spawnEgg.ts', ['paintSpawnEgg'])

fs.rmSync(OUT_DIR, { recursive: true, force: true })

const written = []
const sheet = skin.paintCompanion(SCALE)
written.push({
  key: 'main',
  file: 'kohane.png',
  bytes: writePng(path.join(OUT_DIR, 'kohane.png'), sheet),
  width: sheet.width,
  height: sheet.height,
})

const eggCanvas = egg.paintSpawnEgg(SCALE * 2)
written.push({
  key: 'spawn_egg',
  file: 'kohane_spawn_egg.png',
  bytes: writePng(path.join(OUT_DIR, 'kohane_spawn_egg.png'), eggCanvas),
  width: eggCanvas.width,
  height: eggCanvas.height,
})

const manifest = `/**
 * Where the built-in companion artwork lives.
 *
 * Generated by \`node scripts/make-companion.mjs\` — edit the painter in
 * \`src/core/generators/skin/\`, not this file. \`path\` is what a preset puts in
 * its \`url\`: relative to the app's base URL, and under \`textures/\` so the
 * preset validator accepts it.
 */

export interface CompanionTexture {
  /** Texture slot key on the entity node this PNG belongs in. */
  slot: string
  fileName: string
  /** App-relative path, for a preset's \`url\`. */
  path: string
  width: number
  height: number
  /** SHA-256 of the bytes, so a stale checkout is obvious rather than subtle. */
  digest: string
}

export const COMPANION_TEXTURES: CompanionTexture[] = [
${written
  .map((entry) => {
    const digest = createHash('sha256').update(entry.bytes).digest('hex').slice(0, 16)
    return `  { slot: '${entry.key}', fileName: '${entry.file}', path: '${OUT_REL}/${entry.file}', width: ${entry.width}, height: ${entry.height}, digest: '${digest}' },`
  })
  .join('\n')}
]

/** The texture for one entity slot, or undefined if the build did not write it. */
export function companionTexture(slot: string): CompanionTexture | undefined {
  return COMPANION_TEXTURES.find((texture) => texture.slot === slot)
}
`

fs.writeFileSync(MANIFEST, manifest)

for (const entry of written) {
  console.log(
    `${entry.file.padEnd(28)} ${entry.width}x${entry.height}  ${(entry.bytes.length / 1024).toFixed(1)} KB`,
  )
}
console.log(`\nWrote ${written.length} files to ${path.relative(ROOT, OUT_DIR)} at ${SCALE}x.`)
