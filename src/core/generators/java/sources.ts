/**
 * The Java source tree of an exported mod.
 *
 * This is the part of the builder that cannot pretend the two platforms are
 * alike. A Bedrock block is a JSON file the game reads; a Java block is an
 * object that has to be constructed and handed to a registry while the game is
 * starting, which means real code. So the export is a Gradle project rather
 * than a finished jar — a browser tab cannot run javac — and the honest promise
 * is "everything is written for you, run ./gradlew build".
 *
 * Two decisions keep this manageable:
 *
 *   **Mojang mappings everywhere.** Fabric is generated against
 *   `officialMojangMappings()` rather than Yarn, so one set of templates
 *   compiles on all four loaders instead of Fabric needing its own dialect of
 *   every class name.
 *
 *   **The loader differences are a short list, not a fork.** Registration is
 *   the only thing that genuinely differs — Fabric calls `Registry.register`
 *   directly, the Forge family uses a `DeferredRegister` — so that one method
 *   is written per loader and everything downstream is shared.
 *
 * Anything version-specific (a renamed method, a constructor that went private)
 * lives in the profile's `api` block, never inline here.
 */

import type { ContentNode } from '../../model/types'
import type { VirtualFile } from '../../vfs/types'
import { bool, list, num, str } from '../../kinds/shared'
import type { JavaContext } from './context'
import { constantCase, packagePath, pascalCase, rootPackage } from './ids'
import { isFabricFamily, loaderCode } from './loaderCode'
import type { LoaderCode } from './loaderCode'

function javaFile(pkg: string, className: string, body: string): VirtualFile {
  return {
    path: `src/main/java/${packagePath(pkg)}/${className}.java`,
    origin: { label: `Java · ${className}` },
    body: { type: 'text', value: body },
  }
}

/** Turns a string into a Java string literal, escaping what has to be escaped. */
function lit(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`
}

export interface SourceOutput {
  files: VirtualFile[]
  /** Fully qualified name of the mod's entry class, for the loader metadata. */
  mainClass: string
}

export function emitSources(ctx: JavaContext, stationBlocks: ContentNode[]): SourceOutput {
  const pkg = rootPackage(ctx.project)
  const files: VirtualFile[] = []
  const code = loaderCode(ctx.loader, ctx.profile)
  const fabric = isFabricFamily(ctx.loader)

  files.push(emitModMain(ctx, pkg, fabric, code))
  files.push(emitRegistryHelper(ctx, pkg, fabric, code))
  files.push(emitModItems(ctx, pkg, code))
  files.push(emitModBlocks(ctx, pkg, stationBlocks, code))
  files.push(emitCreativeTab(ctx, pkg, code))

  for (const node of ctx.project.nodes.filter((n) => n.kind === 'crop')) {
    files.push(emitCropBlock(pkg, node))
  }

  const structures = ctx.project.nodes.filter((n) => n.kind === 'structure')
  if (structures.length > 0) files.push(emitStructureFeature(ctx, pkg, structures))

  if (fabric) files.push(emitFabricWorldgen(ctx, pkg))

  return { files, mainClass: `${pkg}.${pascalCase(ctx.project.namespace)}Mod` }
}

// -- entry point -------------------------------------------------------------

function emitModMain(ctx: JavaContext, pkg: string, fabric: boolean, code: LoaderCode): VirtualFile {
  const className = `${pascalCase(ctx.project.namespace)}Mod`
  const hasStructures = ctx.project.nodes.some((n) => n.kind === 'structure')

  const body = fabric
    ? `package ${pkg};

import net.fabricmc.api.ModInitializer;

/**
 * Entry point. Fabric calls onInitialize once, on both client and server, after
 * the registries are open — which is why every registration below is a plain
 * static-initialiser touch rather than an event subscription.
 *
 * Generated by the add-on builder. Re-exporting overwrites this file, so put
 * hand-written code in a new class instead of editing this one.
 */
public class ${className} implements ModInitializer {
    public static final String MOD_ID = ${lit(ctx.modId)};

    @Override
    public void onInitialize() {
        ModItems.register();
        ModBlocks.register();
        ModCreativeTabs.register();
        ModStations.register();${hasStructures ? '\n        ModStructures.register();' : ''}
        ModWorldgen.register();
    }
}
`
    : (() => {
        const ctor = code.modConstructor(className)
        const annotation = code.family === 'forge' ? '@Mod' : '@Mod'
        return `package ${pkg};

${code.modImports.map((name) => `import ${name};`).join('\n')}

/**
 * Entry point. The Forge family constructs the mod class with the mod event
 * bus, and every DeferredRegister has to be attached to it here — a register
 * that is never attached simply never fires, with no error to notice.
 *
 * Generated by the add-on builder. Re-exporting overwrites this file, so put
 * hand-written code in a new class instead of editing this one.
 */
${annotation}(${className}.MOD_ID)
public class ${className} {
    public static final String MOD_ID = ${lit(ctx.modId)};

    ${ctor.signature} {
        ${ctor.busExpression}
        ModItems.REGISTER.register(modBus);
        ModBlocks.REGISTER.register(modBus);
        ModCreativeTabs.REGISTER.register(modBus);
        ModStations.MENUS.register(modBus);${hasStructures ? '\n        ModStructures.FEATURES.register(modBus);' : ''}
    }
}
`
      })()

  return javaFile(pkg, className, body)
}

/**
 * One place that knows how this loader registers things.
 *
 * Fabric hands you the vanilla registries directly; the Forge family insists on
 * a DeferredRegister so entries are created at the right moment in startup.
 * Both are wrapped in the same two-method surface so the callers below read
 * identically whichever loader they were generated for.
 */
function emitRegistryHelper(ctx: JavaContext, pkg: string, fabric: boolean, code: LoaderCode): VirtualFile {
  const rl = ctx.profile.api.resourceLocation('MOD_ID', 'path')
  const modClass = `${pascalCase(ctx.project.namespace)}Mod`

  const body = fabric
    ? `package ${pkg};

import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.block.Block;

import java.util.function.Supplier;

/**
 * Registration, Fabric flavour.
 *
 * The Supplier returned here is immediate rather than deferred — Fabric has
 * already opened the registries by the time onInitialize runs — but it keeps the
 * call sites identical to the Forge build, which is the whole point.
 */
public final class ModRegistry {
    public static final String MOD_ID = ${modClass}.MOD_ID;

    private ModRegistry() {}

    public static ResourceLocation id(String path) {
        return ${rl};
    }

    public static Supplier<Item> item(String path, Supplier<Item> factory) {
        Item registered = Registry.register(BuiltInRegistries.ITEM, id(path), factory.get());
        return () -> registered;
    }

    public static Supplier<Block> block(String path, Supplier<Block> factory) {
        Block registered = Registry.register(BuiltInRegistries.BLOCK, id(path), factory.get());
        return () -> registered;
    }
}
`
    : `package ${pkg};

import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.block.Block;
${code.registryImports.map((name) => `import ${name};`).join('\n')}

import java.util.function.Supplier;

/**
 * Registration, Forge-family flavour.
 *
 * DeferredRegister exists because the Forge family constructs mods before the
 * registries are open, so an entry created eagerly would be created too early.
 * Every register in this class is attached to the mod bus in ${modClass}.
 */
public final class ModRegistry {
    public static final String MOD_ID = ${modClass}.MOD_ID;

    private ModRegistry() {}

    public static ResourceLocation id(String path) {
        return ${rl};
    }

    public static DeferredRegister<Item> items() {
        return DeferredRegister.create(Registries.ITEM, MOD_ID);
    }

    public static DeferredRegister<Block> blocks() {
        return DeferredRegister.create(Registries.BLOCK, MOD_ID);
    }
}
`

  return javaFile(pkg, 'ModRegistry', body)
}

// -- items -------------------------------------------------------------------

/** `Item.Properties()` for one item node, including its food and stack size. */
function itemProperties(ctx: JavaContext, node: ContentNode): string {
  const parts: string[] = ['new Item.Properties()']
  const stack = Math.round(num(node.data, 'maxStackSize', 64))
  if (stack !== 64) parts.push(`.stacksTo(${Math.max(1, Math.min(99, stack))})`)

  if (bool(node.data, 'isFood')) {
    const nutrition = Math.round(num(node.data, 'nutrition', 4))
    const saturation = num(node.data, 'saturation', 0.6)
    const method = ctx.profile.api.foodSaturationMethod
    const builder = [
      'new FoodProperties.Builder()',
      `.nutrition(${nutrition})`,
      `.${method}(${saturation}F)`,
    ]
    if (bool(node.data, 'canAlwaysEat')) builder.push('.alwaysEdible()')
    parts.push(`.food(${builder.join('')}.build())`)
  }
  if (bool(node.data, 'glint')) parts.push('.fireResistant()')
  return parts.join('')
}

function emitModItems(ctx: JavaContext, pkg: string, code: LoaderCode): VirtualFile {
  const fabric = isFabricFamily(ctx.loader)
  const items = ctx.project.nodes.filter((n) => n.kind === 'item')
  const crops = ctx.project.nodes.filter(
    (n) => n.kind === 'crop' && bool(n.data, 'generateSeed', true),
  )

  const lines: string[] = []
  const names: string[] = []

  for (const node of items) {
    const constant = constantCase(node.name)
    names.push(constant)
    lines.push(
      fabric
        ? `    public static final Supplier<Item> ${constant} =\n            ModRegistry.item(${lit(node.name)}, () -> new Item(${itemProperties(ctx, node)}));`
        : `    public static final ${code.holderType('Item', 'Item')} ${constant} =\n            REGISTER.register(${lit(node.name)}, () -> new Item(${itemProperties(ctx, node)}));`,
    )
  }

  // A crop's seed is an item on Java, not a component of the block — it has to
  // know which block it plants, so it is registered after ModBlocks is loaded.
  for (const node of crops) {
    const seedName = str(node.data, 'seedName').trim() || `${node.name}_seeds`
    const constant = constantCase(seedName)
    names.push(constant)
    const blockRef = fabric
      ? `ModBlocks.${constantCase(node.name)}.get()`
      : `ModBlocks.${constantCase(node.name)}.get()`
    lines.push(
      fabric
        ? `    public static final Supplier<Item> ${constant} =\n            ModRegistry.item(${lit(seedName)}, () -> new ItemNameBlockItem(${blockRef}, new Item.Properties()));`
        : `    public static final ${code.holderType('Item', 'Item')} ${constant} =\n            REGISTER.register(${lit(seedName)}, () -> new ItemNameBlockItem(${blockRef}, new Item.Properties()));`,
    )
  }

  const header = fabric
    ? `package ${pkg};

import net.minecraft.world.food.FoodProperties;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemNameBlockItem;

import java.util.function.Supplier;
`
    : `package ${pkg};

import net.minecraft.world.food.FoodProperties;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemNameBlockItem;
${code.registryImports.map((name) => `import ${name};`).join('\n')}

import java.util.function.Supplier;
`

  const body = `${header}
/**
 * Every item this add-on adds.
 *
 * Order matters more than it looks: a seed item holds a reference to the crop
 * block it plants, so ModBlocks has to have finished before those lines run.
 * Touching ModBlocks first in register() is what guarantees that.
 *
 * Generated by the add-on builder.
 */
public final class ModItems {
${fabric ? '' : '    public static final DeferredRegister<Item> REGISTER = ModRegistry.items();\n'}
${lines.join('\n\n') || '    // This add-on adds no items.'}

    private ModItems() {}

    public static void register() {
        // Referencing the class is enough to run its static initialiser.
    }

    public static java.util.List<${code.holderType('Item', 'Item')}> all() {
        return java.util.List.of(${names.join(', ')});
    }
}
`

  return javaFile(pkg, 'ModItems', body)
}

// -- blocks ------------------------------------------------------------------

/** `BlockBehaviour.Properties` for one block node. */
function blockProperties(node: ContentNode): string {
  const parts: string[] = ['BlockBehaviour.Properties.of()']
  const destroy = num(node.data, 'destroyTime', 1.5)
  const resistance = num(node.data, 'explosionResistance', 3)
  if (destroy < 0) parts.push('.strength(-1.0F, 3600000.0F)')
  else parts.push(`.strength(${destroy}F, ${resistance}F)`)

  const light = Math.round(num(node.data, 'lightEmission', 0))
  if (light > 0) parts.push(`.lightLevel(state -> ${Math.min(15, light)})`)

  const friction = num(node.data, 'friction', 0.6)
  if (friction !== 0.6) parts.push(`.friction(${friction}F)`)

  if (!bool(node.data, 'solid', true)) parts.push('.noCollission()')
  if (str(node.data, 'renderMethod', 'opaque') !== 'opaque') parts.push('.noOcclusion()')
  return parts.join('')
}

function emitModBlocks(ctx: JavaContext, pkg: string, stationBlocks: ContentNode[], code: LoaderCode): VirtualFile {
  const fabric = isFabricFamily(ctx.loader)
  const stationIds = new Set(stationBlocks.map((node) => node.id))
  const blocks = ctx.project.nodes.filter((n) => n.kind === 'block')
  const crops = ctx.project.nodes.filter((n) => n.kind === 'crop')

  const lines: string[] = []
  const itemised: string[] = []

  for (const node of blocks) {
    const constant = constantCase(node.name)
    const ctor = stationIds.has(node.id)
      ? `new StationBlock(${blockProperties(node)}, ${lit(node.name)})`
      : `new Block(${blockProperties(node)})`
    lines.push(
      fabric
        ? `    public static final Supplier<Block> ${constant} =\n            ModRegistry.block(${lit(node.name)}, () -> ${ctor});`
        : `    public static final ${code.holderType('Block', 'Block')} ${constant} =\n            REGISTER.register(${lit(node.name)}, () -> ${ctor});`,
    )
    itemised.push(constant)
  }

  for (const node of crops) {
    const constant = constantCase(node.name)
    const className = `${pascalCase(node.name)}CropBlock`
    lines.push(
      fabric
        ? `    public static final Supplier<Block> ${constant} =\n            ModRegistry.block(${lit(node.name)}, ${className}::new);`
        : `    public static final ${code.holderType('Block', 'Block')} ${constant} =\n            REGISTER.register(${lit(node.name)}, ${className}::new);`,
    )
    // A crop block has no block item: you plant it with its seed, exactly the
    // way wheat works, so registering one would put a stray item in creative.
  }

  const header = fabric
    ? `package ${pkg};

import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.state.BlockBehaviour;

import java.util.function.Supplier;
`
    : `package ${pkg};

import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.state.BlockBehaviour;
${code.registryImports.map((name) => `import ${name};`).join('\n')}

import java.util.function.Supplier;
`

  const blockItems = itemised
    .map((constant) =>
      fabric
        ? `        Registry.register(BuiltInRegistries.ITEM, ModRegistry.id(${lit(
            blocks.find((n) => constantCase(n.name) === constant)!.name,
          )}), new BlockItem(${constant}.get(), new Item.Properties()));`
        : `        ModItems.REGISTER.register(${lit(
            blocks.find((n) => constantCase(n.name) === constant)!.name,
          )}, () -> new BlockItem(${constant}.get(), new Item.Properties()));`,
    )
    .join('\n')

  const body = `${header}
/**
 * Every block this add-on adds, and the item you hold in your hand for each.
 *
 * Crops are the exception and get no block item on purpose: you plant a crop
 * with its seed, so registering an item for the block itself would leave a
 * stray entry in the creative inventory that plants nothing.
 *
 * Generated by the add-on builder.
 */
public final class ModBlocks {
${fabric ? '' : '    public static final DeferredRegister<Block> REGISTER = ModRegistry.blocks();\n'}
${lines.join('\n\n') || '    // This add-on adds no blocks.'}

    private ModBlocks() {}

    public static void register() {
        registerBlockItems();
    }

    private static void registerBlockItems() {
${blockItems || '        // Nothing to give an item form.'}
    }

    public static java.util.List<${code.holderType('Block', 'Block')}> all() {
        return java.util.List.of(${[...blocks, ...crops].map((n) => constantCase(n.name)).join(', ')});
    }
}
`

  return javaFile(pkg, 'ModBlocks', body)
}

