/**
 * One class per crop, extending vanilla's CropBlock.
 *
 * This is the clearest single example of Java being less work than Bedrock for
 * the same feature. On Bedrock a growing crop needs a scripted custom component
 * — the modern block parser dropped data-driven block events — so the builder
 * has to emit JavaScript and add a script module to the manifest. On Java,
 * extending CropBlock inherits random-tick growth, bonemeal, farmland
 * trampling, and the "is it ripe" check, and the class below only has to say
 * how many stages there are and which item is the seed.
 */
function emitCropBlock(pkg: string, node: ContentNode): VirtualFile {
  const className = `${pascalCase(node.name)}CropBlock`
  const stages = Math.max(2, Math.round(num(node.data, 'stages', 4)))
  const maxAge = stages - 1
  const seedName = str(node.data, 'seedName').trim() || `${node.name}_seeds`

  const body = `package ${pkg};

import com.mojang.serialization.MapCodec;
import net.minecraft.world.item.ItemLike;
import net.minecraft.world.level.block.CropBlock;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.properties.IntegerProperty;

/**
 * ${node.displayName} — ${stages} growth stages, ages 0 to ${maxAge}.
 *
 * Growth, bonemeal and the drop table all come from CropBlock. The only things
 * this class states are the stage count and the seed item.
 *
 * Generated by the add-on builder.
 */
public class ${className} extends CropBlock {
    public static final int MAX_AGE = ${maxAge};
    public static final IntegerProperty AGE = IntegerProperty.create("age", 0, MAX_AGE);

    public ${className}() {
        super(BlockBehaviour.Properties.of()
                .noCollission()
                .randomTicks()
                .instabreak()
                .sound(SoundType.CROP)
                .pushReaction(net.minecraft.world.level.material.PushReaction.DESTROY));
    }

    @Override
    public IntegerProperty getAgeProperty() {
        return AGE;
    }

    @Override
    public int getMaxAge() {
        return MAX_AGE;
    }

    @Override
    protected ItemLike getBaseSeedId() {
        return ModItems.${constantCase(seedName)}.get();
    }

    @Override
    protected MapCodec<? extends CropBlock> codec() {
        return simpleCodec(properties -> new ${className}());
    }

    @Override
    protected void createBlockStateDefinition(net.minecraft.world.level.block.state.StateDefinition.Builder<net.minecraft.world.level.block.Block, net.minecraft.world.level.block.state.BlockState> builder) {
        builder.add(AGE);
    }
}
`
  return javaFile(pkg, className, body)
}

