/**
 * The painted structure grid, baked into a Feature class.
 *
 * Java normally places a structure from a binary `.nbt` file written by the
 * in-game structure block, which this builder has no way to produce. Placing
 * the blocks from code sidesteps the format entirely, and for the small
 * hand-painted structures the builder makes, the array below is smaller than
 * the NBT would have been.
 */
function emitStructureFeature(ctx: JavaContext, pkg: string, nodes: ContentNode[]): VirtualFile {
  const entries = nodes.map((node) => {
    const grid = node.data.grid as { size?: number[]; cells?: unknown[] } | undefined
    const size = Array.isArray(grid?.size) ? grid!.size! : [1, 1, 1]
    const cells = Array.isArray(grid?.cells) ? grid!.cells! : []
    const blocks = cells
      .map((cell) => (typeof cell === 'string' ? cell.trim() : ''))
      .map((cell) => (cell ? lit(cell) : 'null'))
    return `        LAYOUTS.put(${lit(node.name)}, new Layout(${size[0]}, ${size[1]}, ${size[2]}, new String[]{\n                ${blocks.join(', ')}\n        }));`
  })

  const body = `package ${pkg};

import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.level.WorldGenLevel;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Painted structures, placed block by block from a baked layout.
 *
 * The array is in the same order the painter uses: X fastest, then Z, then Y,
 * so index = (y * depth + z) * width + x. Getting that order wrong produces a
 * structure that is subtly transposed and very hard to diagnose, which is why
 * it is stated here rather than left implicit.
 *
 * Generated by the add-on builder.
 */
public final class ModStructures {
    public record Layout(int width, int height, int depth, String[] blocks) {}

    public static final Map<String, Layout> LAYOUTS = new LinkedHashMap<>();

    static {
${entries.join('\n')}
    }

    private ModStructures() {}

    public static void register() {
        // Nothing to register: the layouts are placed by place() below, which
        // your own feature or command can call.
    }

    /** Places one layout with its north-west-bottom corner at {@code origin}. */
    public static void place(WorldGenLevel level, BlockPos origin, String name) {
        Layout layout = LAYOUTS.get(name);
        if (layout == null) return;

        for (int y = 0; y < layout.height(); y++) {
            for (int z = 0; z < layout.depth(); z++) {
                for (int x = 0; x < layout.width(); x++) {
                    String id = layout.blocks()[(y * layout.depth() + z) * layout.width() + x];
                    if (id == null) continue;
                    BlockState state = stateOf(id);
                    if (state == null) continue;
                    level.setBlock(origin.offset(x, y, z), state, 3);
                }
            }
        }
    }

    private static BlockState stateOf(String id) {
        ResourceLocation key = ${ctx.profile.api.parseResourceLocation('id')};
        Block block = BuiltInRegistries.BLOCK.get(key);
        return block == Blocks.AIR ? null : block.defaultBlockState();
    }
}
`

  return javaFile(pkg, 'ModStructures', body)
}

// -- Fabric world generation --------------------------------------------------

/**
 * Attaching features to existing biomes, Fabric flavour.
 *
 * Forge and NeoForge both read a `biome_modifier` JSON file from the data pack,
 * so they need no code for this at all. Fabric has no such file and does it
 * from `BiomeModifications`, which is what this class is for. A plain data pack
 * has neither, which is why the capability matrix calls scattering "partial"
 * on that route.
 */
function emitFabricWorldgen(ctx: JavaContext, pkg: string): VirtualFile {
  const placements = ctx.project.nodes.filter(
    (node) =>
      (node.kind === 'scatter' || node.kind === 'tree') && bool(node.data, 'worldPlace', true),
  )

  const registrations = placements
    .map((node) => {
      const tags = [...list(node.data, 'biomeTags'), ...list(node.data, 'biomeTagsCustom')]
      const selector =
        tags.length === 0 || tags.includes('overworld')
          ? 'BiomeSelectors.foundInOverworld()'
          : `BiomeSelectors.tag(TagKey.create(Registries.BIOME, ResourceLocation.parse("minecraft:is_${tags[0]}")))`
      return `        BiomeModifications.addFeature(
                ${selector},
                GenerationStep.Decoration.VEGETAL_DECORATION,
                ResourceKey.create(Registries.PLACED_FEATURE, ModRegistry.id(${lit(node.name)})));`
    })
    .join('\n\n')

  const body = `package ${pkg};

import net.fabricmc.fabric.api.biome.v1.BiomeModifications;
import net.fabricmc.fabric.api.biome.v1.BiomeSelectors;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.tags.TagKey;
import net.minecraft.world.level.levelgen.GenerationStep;

/**
 * Fabric has no data-driven biome modifier, so the placed features written into
 * the data pack are attached to biomes here instead.
 *
 * Generated by the add-on builder.
 */
public final class ModWorldgen {
    private ModWorldgen() {}

    public static void register() {
${registrations || '        // This add-on places nothing in the world.'}
    }
}
`

  return javaFile(pkg, 'ModWorldgen', body)
}
