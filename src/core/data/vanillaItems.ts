/**
 * A catalogue of vanilla identifiers for the Item Browser.
 *
 * Deliberately curated rather than exhaustive: these are the things people
 * actually reach for when writing a recipe, grouped the way the creative
 * inventory groups them. Anything missing can still be typed by hand into a
 * slot, so the list is a shortcut, never a limit.
 *
 * No vanilla artwork is shipped or referenced — the browser draws its own tile
 * for these, and only textures you made yourself have a preview image.
 */

export interface VanillaItem {
  id: string
  label: string
  group: string
}

function group(name: string, ids: string[]): VanillaItem[] {
  return ids.map((id) => ({
    id: `minecraft:${id}`,
    label: id.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase()),
    group: name,
  }))
}

